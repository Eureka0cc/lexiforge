package com.justinsight.lexiforge.db;

import org.junit.jupiter.api.Test;

import java.nio.charset.StandardCharsets;

import static org.assertj.core.api.Assertions.assertThat;

class SchemaContractTest {
    @Test void businessIdsUseBigintWithoutDatabaseSequences() throws Exception {
        try (var in = getClass().getResourceAsStream("/db/migration/V1__initial_schema.sql")) {
            assertThat(in).isNotNull();
            String sql = new String(in.readAllBytes(), StandardCharsets.UTF_8).toUpperCase();
            assertThat(sql).doesNotMatch("(?s).*\\bSERIAL\\b.*")
                    .doesNotContain("GENERATED BY DEFAULT AS IDENTITY", "NEXTVAL(");
            assertThat(sql).contains("ID BIGINT PRIMARY KEY", "USER_ID BIGINT");
        }
    }

    @Test void aiRedesignMigrationIsAdditiveAndSenseAware() throws Exception {
        try (var in = getClass().getResourceAsStream("/db/migration/V3__ai_translation_redesign.sql")) {
            assertThat(in).isNotNull();
            String sql = new String(in.readAllBytes(), StandardCharsets.UTF_8).toUpperCase();
            assertThat(sql).contains("CREATE TABLE AI_REQUEST", "CREATE TABLE TRANSLATION_LOOKUP",
                    "ALTERNATIVES_JSON", "SENSE_KEY", "LOOKUP_COUNT");
            assertThat(sql).doesNotContain("DROP TABLE TRANSLATION", "DROP TABLE VOCABULARY_ITEM");
        }
    }
}
